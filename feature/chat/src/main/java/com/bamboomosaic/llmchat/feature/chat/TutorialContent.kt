# 2. 软件专业术语解读
很多名词是AI对话圈通用词汇，这里简单看懂：
- **Token**：大模型读取文字的计量单位，一句话会拆成多个token，token越多，消耗费用越高。中文大概1个汉字≈2个token。
- **上下文**：AI能“记住”的本轮聊天全部内容，上下文有上限，装满之后需要压缩。
- **上下文压缩**：把前面的对话精简摘要，腾出空间继续聊天，避免超限。
- **系统提示词（模式）**：给AI定下身份、规则，比如翻译官、代码审查，决定AI的说话风格。
- **会话**：一次独立对话，不同会话互相隔离，AI不会跨会话记忆内容。
- **省Token模式**：软件内置优化策略，精简提示词、限制输出，降低消耗。
- **API Key**：访问云端大模型的身份钥匙，相当于你的账号通行证。
